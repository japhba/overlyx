#!/usr/bin/env node
// The emoji keyboard's data (packages/client/src/editor/emoji/emojidata.ts) from Unicode's emoji-test.txt
// (https://unicode.org/Public/emoji/latest/emoji-test.txt, Unicode licence):
//   node scripts/gen-emoji-data.mjs emoji-test.txt
// One row per emoji, its variants after it: the skin tones (one tone throughout), and the colours of the
// families below (hearts, circles, squares, books, …). Only emoji up to MAX_VERSION, which the emoji
// fonts draw (Noto Color Emoji).
import fs from 'node:fs';

const MAX_VERSION = 16.0;
const COLOUR_FAMILIES = [
  '❤️ 🩷 🧡 💛 💚 💙 🩵 💜 🤎 🖤 🩶 🤍',
  '🔴 🟠 🟡 🟢 🔵 🟣 🟤 ⚫ ⚪',
  '🟥 🟧 🟨 🟩 🟦 🟪 🟫 ⬛ ⬜',
  '📕 📙 📒 📗 📘 📓 📔',
  '🔶 🔷 🔸 🔹',
  '🍎 🍏',
  '🐈 🐈‍⬛',
  '🐦 🐦‍⬛',
  '🐻 🐻‍❄️',
  '🍋 🍋‍🟩',
  '🍄 🍄‍🟫',
].map(s => s.split(' '));
const TONES = ['1F3FB', '1F3FC', '1F3FD', '1F3FE', '1F3FF'];

const src = fs.readFileSync(process.argv[2], 'utf8');
const header = /^# Version: (.*)$/m.exec(src)?.[1] ?? '?';
const groups = []; // { name, rows: { e, name, cps, v: [] }[] }
let group = null;
const byKey = new Map();
const toned = [];
for (const line of src.split('\n')) {
  const g = /^# group: (.*)$/.exec(line);
  if (g) { if (g[1] === 'Component') { group = null; continue; } group = { name: g[1], rows: [] }; groups.push(group); continue; }
  const m = /^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*(\S+)\s+E(\d+\.\d+)\s+(.*)$/.exec(line);
  if (!m || !group) continue;
  const cps = m[1].split(' ');
  if (Number(m[3]) > MAX_VERSION) continue;
  const e = String.fromCodePoint(...cps.map(c => parseInt(c, 16)));
  const tones = cps.filter(c => TONES.includes(c));
  if (tones.length) { if (new Set(tones).size === 1) toned.push({ e, cps, tone: TONES.indexOf(tones[0]) }); continue; }
  const row = { e, name: m[4].trim(), cps, v: [] };
  group.rows.push(row);
  byKey.set(cps.filter(c => c !== 'FE0F').join(' '), row);
}
for (const t of toned) {
  const base = byKey.get(t.cps.filter(c => c !== 'FE0F' && !TONES.includes(c)).join(' '));
  if (base) base.v[t.tone] = t.e;
}
// colour families: the first emoji's row takes the others as variants
const all = new Map(groups.flatMap(g => g.rows.map(r => [r.e, r])));
const gone = new Set();
for (const fam of COLOUR_FAMILIES) {
  const rows = fam.map(e => all.get(e)).filter(Boolean);
  if (rows.length < 2) continue;
  rows[0].v = rows.slice(1).map(r => r.e);
  rows[0].family = true;
  for (const r of rows.slice(1)) gone.add(r.e);
}
let out = `/**
 * The emoji keyboard's emoji (picker.ts): generated by scripts/gen-emoji-data.mjs from Unicode's
 * emoji-test.txt ${header} (Unicode licence), emoji up to E${MAX_VERSION.toFixed(1)}. Per group, one row per emoji —
 * "emoji<TAB>name[<TAB>variants separated by spaces]" — the variants its skin tones or its colours.
 * Do not edit: run the script again.
 */
export const EMOJI_DATA: [string, string][] = [\n`;
for (const g of groups) {
  const rows = g.rows.filter(r => !gone.has(r.e)).map(r => [r.e, r.name, ...(r.v.filter(Boolean).length ? [r.v.filter(Boolean).join(' ')] : [])].join('\t'));
  out += `  [${JSON.stringify(g.name)}, ${JSON.stringify(rows.join('\n'))}],\n`;
}
out += '];\n';
fs.writeFileSync(new URL('../packages/client/src/editor/emoji/emojidata.ts', import.meta.url), out);
console.log('rows', groups.reduce((n, g) => n + g.rows.length - g.rows.filter(r => gone.has(r.e)).length, 0), 'bytes', Buffer.byteLength(out));
